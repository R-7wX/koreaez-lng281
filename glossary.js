const PARTICLE_SUFFIXES = [
  { suf: '이에요', mean: 'เป็น/คือ' },
  { suf: '예요', mean: 'เป็น/คือ' },
  { suf: '하고', mean: 'และ/กับ' },
  { suf: '은', mean: 'ตัวชี้หัวเรื่อง' },
  { suf: '는', mean: 'ตัวชี้หัวเรื่อง' },
  { suf: '이', mean: 'ตัวชี้ประธาน' },
  { suf: '가', mean: 'ตัวชี้ประธาน' },
  { suf: '을', mean: 'ตัวชี้กรรม' },
  { suf: '를', mean: 'ตัวชี้กรรม' },
  { suf: '에', mean: 'ที่/ใน/ขีด(-)' }
];

function lookupWordThai(rawToken) {
  const tok = String(rawToken || '').replace(/[.,?!~"'()]/g, '').trim();
  if (!tok || !/[가-힣]/.test(tok)) return '';
  if (WORD_GLOSSARY[tok]) return WORD_GLOSSARY[tok];

  // Check month/day patterns like 5월, 26일, 12월
  const mMonth = tok.match(/^(\d+)월$/);
  if (mMonth) return `เดือน ${mMonth[1]}`;
  const mDay = tok.match(/^(\d+)일(.*)$/);
  if (mDay) {
    const rest = mDay[2] ? lookupWordThai(mDay[2]) : '';
    return `วันที่ ${mDay[1]}${rest ? ' + ' + rest : ''}`;
  }
  const mWon = tok.match(/^([\d,]+)원(.*)$/);
  if (mWon) return `${mWon[1]} วอน`;

  // Check Sino compound numbers (e.g. 이십육일, 사천오백, 오삼삼칠)
  if (/^[공영일이삼사오육칠팔구십백천만]+(?:일|월|원|번|층|분|이에요|예요|에)?$/.test(tok)) {
    let suffixMean = '';
    let core = tok;
    for (const p of PARTICLE_SUFFIXES) {
      if (core.endsWith(p.suf) && core.length > p.suf.length) {
        core = core.slice(0, -p.suf.length);
        suffixMean = ' + ' + p.mean;
        break;
      }
    }
    const unitMap = { '일': 'วันที่', '월': 'เดือน', '원': 'วอน', '번': 'เบอร์', '층': 'ชั้น', '분': 'นาที' };
    let unit = '';
    if (unitMap[core.slice(-1)] && core.length > 1) {
      unit = ' ' + unitMap[core.slice(-1)];
      core = core.slice(0, -1);
    }
    const dMap = { '공': '0', '영': '0', '일': '1', '이': '2', '삼': '3', '사': '4', '오': '5', '육': '6', '칠': '7', '팔': '8', '구': '9', '십': 'สิบ', '백': 'ร้อย', '천': 'พัน', '만': 'หมื่น' };
    const decoded = [...core].map(ch => dMap[ch] || ch).join('');
    return `เลข ${decoded}${unit}${suffixMean}`;
  }

  // Try stripping known particles/endings from stem
  for (const p of PARTICLE_SUFFIXES) {
    if (tok.endsWith(p.suf) && tok.length > p.suf.length) {
      const stem = tok.slice(0, -p.suf.length);
      if (WORD_GLOSSARY[stem]) {
        return `${WORD_GLOSSARY[stem]} + ${p.suf}(${p.mean})`;
      }
    }
  }
  return '';
}

function buildWordBreakdownHTML(sentence) {
  if (!sentence || !/[가-힣]/.test(sentence)) return '';
  const tokens = String(sentence).trim().split(/\s+/);
  const chips = [];
  for (const raw of tokens) {
    const clean = raw.replace(/[.,?!~"'()]/g, '').trim();
    if (!clean || !/[가-힣]/.test(clean)) continue;
    const mean = lookupWordThai(clean);
    if (!mean) continue;
    const read = typeof hangulToThai === 'function' ? hangulToThai(clean) : '';
    chips.push(
      `<button type="button" class="wb-chip" onclick="event.stopPropagation(); speak('${clean.replace(/'/g, "\\'")}')">` +
      `<span class="wb-kr kr">${clean}</span>` +
      (read ? `<span class="wb-read th-read">${read}</span>` : '') +
      `<span class="wb-th">${mean}</span>` +
      `</button>`
    );
  }
  if (!chips.length) return '';
  return `<div class="wb-strip"><span class="wb-label">📖 แปลทีละคำ:</span>${chips.join('')}</div>`;
}
